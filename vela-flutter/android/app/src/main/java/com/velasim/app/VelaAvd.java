    static String sanitize(String raw) {
        String s = raw == null ? "vela" : raw.trim();
        if (s.isEmpty()) {
            s = "vela";
        }
        s = s.replaceAll("[^A-Za-z0-9._-]", "-");
        if (s.regionMatches(true, 0, "vela_", 0, 5)) {
            s = s.substring(5);
        }
        if (s.regionMatches(true, 0, "avd_", 0, 4)) {
            s = s.substring(4);
        }
        if (s.isEmpty()) {
            s = "vela";
        }
        return (s.startsWith("-") ? "avd-" : s) + (s.endsWith("-") ? "avd" : "");
    }

    static String displayName(String avdId) {
        String s = avdId.startsWith("miwear_") ? avdId.substring("miwear_".length()) : avdId;
        return "Vortex " + s.replace('_', ' ');
    }

    /** "466x466" / "192x572" -> {466,466}; anything else -> {0,0}. */
    static int[] parseSkin(String skin) {
        int[] out = {0, 0};
        if (skin == null) {
            return out;
        }
        String s = skin.toLowerCase(Locale.ROOT).replace("x", " ").trim();
        String[] parts = s.split("\\s+");
        if (parts.length == 2) {
            out[0] = parseInt(parts[0], 0);
            out[1] = parseInt(parts[1], 0);
        }
        return out;
    }

    static int parseInt(String s, int def) {
        try {
            return Integer.parseInt(s.trim());
        } catch (Exception e) {
            return def;
        }
    }

    /** config.ini wants "<n> MB"; readers want plain megabytes. */
    static int parseRamMb(String v) {
        if (v == null) {
            return 0;
        }
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < v.length(); i++) {
            char c = v.charAt(i);
            if (c >= '0' && c <= '9') {
                sb.append(c);
            } else if (sb.length() > 0) {
                break;
            }
        }
        return parseInt(sb.length() == 0 ? "0" : sb.toString(), 0);
    }

    static String randomUuid() {
        return UUID.randomUUID().toString();
    }

    /** config.ini as JSON, handy for logs. */
    public static String configAsJson(Context ctx, String avdId) {
        return new JSONObject(readIni(new File(directoryFor(ctx, avdId), CONFIG_INI))).toString();
    }
