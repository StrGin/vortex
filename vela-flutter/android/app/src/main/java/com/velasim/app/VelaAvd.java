    /** Every AVD under <code>ANDROID_AVD_HOME</code> with a readable config.ini. */
    public static List<Entry> listAll(Context ctx) {
        List<Entry> out = new ArrayList<>();
        File home = VelaPaths.velaVvdDir(ctx);
        File[] kids = home.listFiles();
        if (kids == null) {
            return out;
        }
        java.util.Arrays.sort(kids);
        for (File d : kids) {
            String n = d.getName();
            if (!d.isDirectory()) {
                continue;
            }
            String suffix = null;
            for (String cand : AVD_SUFFIXES) {
                if (n.endsWith(cand)) {
                    suffix = cand;
                    break;
                }
            }
            if (suffix == null) {
                continue;
            }
            Map<String, String> cfg = readIni(new File(d, CONFIG_INI));
            if (cfg.isEmpty() && !new File(d, AVD_CONF).isFile()) {
                continue;
            }
            String id = cfg.get("AvdId");
            if (id == null || id.isEmpty()) {
                id = n.substring(0, n.length() - suffix.length());
            }
            out.add(new Entry(d, id, cfg));
        }
        return out;
    }

    public static List<Map<String, Object>> listMaps(Context ctx) {
        List<Map<String, Object>> out = new ArrayList<>();
        for (Entry e : listAll(ctx)) {
            out.add(e.toMap());
        }
        return out;
    }

    // ----------------------------------------------------------------- ini io

    /** Flat ini reader used for config.ini / emulator-user.ini / AVD.conf. */
    public static Map<String, String> readIni(File f) {
        Map<String, String> out = new LinkedHashMap<>();
        if (f == null || !f.isFile()) {
            return out;
        }
        BufferedReader r = null;
        try {
            r = new BufferedReader(new InputStreamReader(new java.io.FileInputStream(f), "UTF-8"));
            String line;
            while ((line = r.readLine()) != null) {
                String s = line.trim();
                if (s.isEmpty() || s.startsWith("#") || s.startsWith(";") || s.startsWith("[")) {
                    continue;
                }
                int eq = s.indexOf('=');
                if (eq <= 0) {
                    continue;
                }
                out.put(s.substring(0, eq).trim(), unquote(s.substring(eq + 1).trim()));
            }
        } catch (IOException e) {
            VelaLog.w("avd", "cannot read " + f + ": " + e);
        } finally {
            VelaUtil.closeQuietly(r);
        }
        return out;
    }

    private static String unquote(String v) {
        if (v.length() >= 2 && (v.charAt(0) == '"' && v.charAt(v.length() - 1) == '"'
                || v.charAt(0) == '\'' && v.charAt(v.length() - 1) == '\'')) {
            return v.substring(1, v.length() - 1);
        }
        return v;
    }

    private static void writeIni(File f, Map<String, String> kv, String comment) throws IOException {
        writeIniPairwise(f, kv, comment);
    }

    private static void writeIniPairwise(File f, Map<String, String> kv, String comment)
            throws IOException {
        f.getParentFile().mkdirs();
        Writer w = new OutputStreamWriter(new FileOutputStream(f), "UTF-8");
        try {
            if (comment != null && !comment.isEmpty()) {
                w.write("# " + comment + "\n");
            }
            for (Map.Entry<String, String> e : kv.entrySet()) {
                w.write(e.getKey() + " = " + (e.getValue() == null ? "" : e.getValue()) + "\n");
            }
        } finally {
            w.close();
        }
    }

