    /** Missing required config.ini keys, for the diagnostics sheet. */
    public static List<String> validate(Context ctx, String avdId) {
        List<String> out = new ArrayList<>();
        File dir = directoryFor(ctx, avdId);
        if (!dir.isDirectory()) {
            out.add("avd directory missing: " + dir.getAbsolutePath());
            return out;
        }
        Map<String, String> cfg = readIni(new File(dir, CONFIG_INI));
        for (String key : new String[]{"AvdId", "image.sysdir.1", "skin.name", "skin.path",
                "hw.cpu.arch", "hw.ramSize", "hw.lcd.density"}) {
            String v = cfg.get(key);
            if (v == null || v.trim().isEmpty()) {
                out.add("config.ini missing " + key);
            }
        }
        String sysdir = cfg.get("image.sysdir.1");
        if (sysdir != null && !sysdir.isEmpty()) {
            File d = new File(sysdir);
            for (String n : REQUIRED_IMAGE_FILES) {
                if (!new File(d, n).isFile()) {
                    out.add("image file missing: " + new File(d, n).getName());
                }
            }
        }
        if (!new File(dir, "share").isDirectory()) {
            out.add("share/ missing");
        }
        if (!new File(dir, "data").isDirectory()) {
            out.add("data/ missing");
        }
        if (!new File(dir, SYSTEM_BIN).isFile()) {
            out.add(SYSTEM_BIN + " missing in AVD dir");
        }
        String spath = cfg.get("skin.path");
        if (spath != null && !spath.isEmpty() && !new File(spath).isDirectory()) {
            out.add("skin directory missing: " + spath + " (re-extract engine assets)");
        }
        return out;
    }

    /** A machine-readable dump of what the launcher will see. */
    public static Map<String, Object> inspect(Context ctx, String avdId) {
        File dir = directoryFor(ctx, avdId);
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("avdId", avdId);
        m.put("path", dir.getAbsolutePath());
        m.put("exists", dir.isDirectory());
        m.put("config", readIni(new File(dir, CONFIG_INI)));
        m.put("user", readIni(new File(dir, USER_INI)));
        m.put("hardwareQemuGenerated", new File(dir, HARDWARE_INI).isFile());
        m.put("problems", validate(ctx, avdId));
        return m;
    }

